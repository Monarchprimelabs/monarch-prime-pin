const dictionaries: Record<Language, Record<string, string>> = { en, es, pt };

export function detectDeviceLanguage(): Language {
  try {
    const raw = Platform.OS === 'ios'
      ? NativeModules.SettingsManager?.settings?.AppleLocale
        || NativeModules.SettingsManager?.settings?.AppleLanguages?.[0]
      : NativeModules.I18nManager?.localeIdentifier;
    const tag = typeof raw === 'string' ? raw.toLowerCase() : '';
    if (tag.startsWith('es')) return 'es';
    if (tag.startsWith('pt')) return 'pt';
  } catch {
    // Fall through to English on any detection failure.
  }
  return 'en';
}

type I18nContextValue = {
  language: Language;
  /** Locale string for toLocaleDateString / toLocaleTimeString calls. */
  dateLocale: string;
  setLanguage: (language: Language) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');

  useEffect(() => {
    AsyncStorage.getItem(KEY_LANGUAGE)
      .then(saved => {
        setLanguageState(
          saved === 'es' || saved === 'en' || saved === 'pt' ? saved : detectDeviceLanguage(),
        );
      })
      .catch(() => setLanguageState(detectDeviceLanguage()));
  }, []);

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    AsyncStorage.setItem(KEY_LANGUAGE, next).catch(() => undefined);
  };

  const value = useMemo<I18nContextValue>(() => ({
    language,
    dateLocale: language === 'es' ? 'es-MX' : language === 'pt' ? 'pt-BR' : 'en-US',
    setLanguage,
    t: (key, vars) => {
      let text = dictionaries[language][key] ?? en[key] ?? key;
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          text = text.split(`{${name}}`).join(String(replacement));
        }
      }
      return text;
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside LanguageProvider');
  return value;
}
